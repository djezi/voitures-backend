package com.example.voituresbackend.service;


import com.example.voituresbackend.entities.Categorie;
import com.example.voituresbackend.repos.CategorieRepository;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class CategorieService {

    private final CategorieRepository categorieRepository;

    public CategorieService(CategorieRepository categorieRepository) {
        this.categorieRepository = categorieRepository;
    }

    public List<Categorie> getAll() {
        return categorieRepository.findAll();
    }

    public Categorie getById(Long id) {
        return categorieRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Catégorie introuvable"));
    }

    public Categorie create(Categorie c) {
        c.setIdCat(null); // the id is generated by MySQL
        return categorieRepository.save(c);
    }

    public Categorie update(Long id, Categorie c) {
        getById(id); // 404 if it does not exist
        c.setIdCat(id);
        return categorieRepository.save(c);
    }
}