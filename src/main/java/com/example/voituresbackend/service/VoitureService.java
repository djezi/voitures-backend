package com.example.voituresbackend.service;


import com.example.voituresbackend.entities.Voiture;
import com.example.voituresbackend.repos.VoitureRepository;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class VoitureService {

    private final VoitureRepository voitureRepository;

    public VoitureService(VoitureRepository voitureRepository) {
        this.voitureRepository = voitureRepository;
    }

    public List<Voiture> getAll() {
        return voitureRepository.findAll();
    }

    public Voiture getById(Long id) {
        return voitureRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Voiture introuvable"));
    }

    public Voiture create(Voiture v) {
        v.setIdVoiture(null); // the id is generated by MySQL
        return voitureRepository.save(v);
    }

    public Voiture update(Long id, Voiture v) {
        getById(id); // 404 if it does not exist
        v.setIdVoiture(id);
        return voitureRepository.save(v);
    }

    public void delete(Long id) {
        getById(id);
        voitureRepository.deleteById(id);
    }

    public List<Voiture> getByCategorie(Long idCat) {
        return voitureRepository.findByCategorieIdCat(idCat);
    }

    public List<Voiture> searchByNom(String nom) {
        return voitureRepository.findByNomVoitureContainingIgnoreCase(nom);
    }
}